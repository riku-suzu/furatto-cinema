/** 緯度経度から近い順にn件の都道府県コードを返す（住所に都道府県名がない場合のフォールバック） */
export function getNearbyPrefCodes(lat: number, lng: number, n: number): string[] {
  return PREF_CENTROIDS
    .map(([code, cLat, cLng]) => ({ code, d: Math.hypot(lat - cLat, lng - cLng) }))
    .sort((a, b) => a.d - b.d)
    .slice(0, n)
    .map((e) => e.code);
}
